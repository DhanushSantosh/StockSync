export type Language = "en" | "hi";
const storageKey = "stocksync-language";

function saved(): Language {
  try {
    return localStorage.getItem(storageKey) === "hi" ? "hi" : "en";
  } catch {
    return "en";
  }
}

let language = saved();
export const currentLanguage = () => language;

export function setLanguage(next: Language) {
  try {
    localStorage.setItem(storageKey, next);
  } catch {
    // Without storage the choice just lasts until the page reloads.
  }
  language = next;
  location.reload();
}

export const t = (text: string) =>
  language === "hi" ? (hindi[text] ?? text) : text;
